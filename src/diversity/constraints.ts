// 按 archetype 取约束规则：子串命中第一个 key 即用，否则兜底。
export function ruleFor(archetype: string): ArchetypeRule {
  for (const key of Object.keys(ARCHETYPE_RULES)) {
    if (archetype.includes(key)) return ARCHETYPE_RULES[key]
  }
  return DEFAULT_RULE
}

// 兜底主题：未命中 / 模糊输入。用"氛围感情绪片"——最具代表性、最百搭的一类。
export const DEFAULT_THEME = THEMES[0]

// 严格匹配：命中（精确主题名 / 关键词 / 主题名子串）返回主题，未命中返回 null（不回退默认）。
// 供 CLI 校验「这个主题到底认不认」用——既支持简写/关键词（如"氛围感"），又能挡住真正的拼错。
export function matchTheme(themeOrVibe: string): Theme | null {
  if (!themeOrVibe) return null
  for (const t of THEMES) {
    if (t.name === themeOrVibe) return t
  }
  for (const t of THEMES) {
    if (t.keywords.some((k) => themeOrVibe.includes(k)) || themeOrVibe.includes(t.name)) return t
  }
  return null
}

// 按主题名或 vibe 词匹配；未命中走兜底（Planner 的模糊输出走这条）。
export function themeFor(themeOrVibe: string): Theme {
  return matchTheme(themeOrVibe) ?? DEFAULT_THEME
}

export const THEME_NAMES = THEMES.map((t) => t.name)
